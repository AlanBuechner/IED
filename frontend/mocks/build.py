"""build.py - helper for the M0 static review mocks (frontend/mocks/).

	python -I frontend/mocks/build.py icons   regenerate css/codicons.css from third_party/codicons
	python -I frontend/mocks/build.py lint    ASCII only, tab indentation, no raw colors outside theme.css
	python -I frontend/mocks/build.py shots [prefix]  screenshots at 1920x1080, 1366x768, 390x844 (Playwright)
	python -I frontend/mocks/build.py all     icons + lint + shots

Icons: only the codicons the mocks reference (class "ci-<name>") are embedded, as data-URI masks,
so the mocks open straight from disk with no server and no font build.
"""

import re
import sys
import urllib.parse
from pathlib import Path

MOCKS = Path(__file__).resolve().parent
FRONTEND = MOCKS.parent
REPO = FRONTEND.parent
CODICONS = REPO / "third_party" / "codicons"
ICON_CSS = MOCKS / "css" / "codicons.css"
SHOT_DIR = MOCKS / "screenshots"

DESKTOP_L = ("1920x1080", 1920, 1080, 1, False)
DESKTOP_S = ("1366x768", 1366, 768, 1, False)
PHONE = ("390x844", 390, 844, 2, True)
ALL_SIZES = (DESKTOP_L, DESKTOP_S, PHONE)

# (page, query, shot name, sizes)
SHOTS = [
	("00-tokens.html", "", "00-tokens", (DESKTOP_L,)),
	("01-editor.html", "", "01-editor", ALL_SIZES),
	("01-editor.html", "?syntax=grayscale", "01-editor-grayscale", (DESKTOP_L,)),
	("02-chat.html", "", "02-chat", ALL_SIZES),
	("03-diff-review.html", "", "03-diff-review", (DESKTOP_L, DESKTOP_S)),
	("03-diff-review.html", "?step=notification", "03-diff-review-1-notification", (PHONE,)),
	("03-diff-review.html", "?step=changes", "03-diff-review-2-changes", (PHONE,)),
	("03-diff-review.html", "?step=diff", "03-diff-review-3-diff", (PHONE,)),
	("04-settings-model-groups.html", "", "04-settings-model-groups", ALL_SIZES),
	("05-git.html", "", "05-git", ALL_SIZES),
	("06-profiler.html", "?view=threads", "06-profiler-threads", ALL_SIZES),
	("06-profiler.html", "?view=tasks", "06-profiler-tasks", ALL_SIZES),
]

# icons that stylesheets use directly (pseudo-elements), exposed as :root { --ic-<name> }
CSS_ICONS = ("chevron-down", "chevron-right", "check")

TEXT_SUFFIXES ={".css", ".html", ".js", ".py", ".md"}
INDENT_SUFFIXES = {".css", ".html", ".js", ".py"}
RAW_COLOR = re.compile(r"(?<![\w&])#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})\b|\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch)\(")


def icon_names():
	names = set()
	for path in list(MOCKS.glob("*.html")) + list((MOCKS / "js").glob("*.js")):
		names.update(re.findall(r"\bci-([a-z0-9]+(?:-[a-z0-9]+)*)", path.read_text(encoding="ascii")))
	return sorted(names)


def svg_data_uri(svg_text):
	svg = re.sub(r"\s+", " ", svg_text).strip()
	svg = re.sub(r'\s(?:width|height|fill)="[^"]*"', "", svg, count=0)
	svg = svg.replace('"', "'")
	return "data:image/svg+xml," + urllib.parse.quote(svg, safe=" /:=',.-")


def build_icons():
	icons_dir = CODICONS / "src" / "icons"
	if not icons_dir.is_dir():
		sys.exit(f"codicons not found at {icons_dir} - run: powershell -NoProfile -ExecutionPolicy Bypass -File tools/fetch-deps.ps1")
	upstream = (CODICONS / "UPSTREAM_COMMIT.txt").read_text(encoding="utf-8").strip()
	lines = [
		"/*",
		"\tcodicons.css - GENERATED by `python -I frontend/mocks/build.py icons`. Do not edit.",
		f"\tSource: third_party/codicons ({upstream}).",
		"\tIcons: Microsoft vscode-codicons, CC BY 4.0 (https://github.com/microsoft/vscode-codicons).",
		"\tEach rule sets --ci to a mask image; .ci in shell.css paints it with currentColor.",
		"*/",
	]
	missing = []
	uris = {}
	for name in sorted(set(icon_names()) | set(CSS_ICONS)):
		svg_path = icons_dir / f"{name}.svg"
		if not svg_path.is_file():
			missing.append(name)
			continue
		uris[name] = svg_data_uri(svg_path.read_text(encoding="utf-8"))
	lines.append(":root {")
	lines.extend(f'\t--ic-{name}: url("{uris[name]}");' for name in CSS_ICONS if name in uris)
	lines.append("}")
	lines.extend(f".ci-{name} {{ --ci: var(--ic-{name}); }}" if name in CSS_ICONS else f'.ci-{name} {{ --ci: url("{uri}"); }}' for name, uri in uris.items())
	ICON_CSS.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
	print(f"icons: wrote {len(uris)} icons to {ICON_CSS.relative_to(REPO)}")
	if missing:
		sys.exit("icons: unknown codicon names: " + ", ".join(missing))


def lint_file(path):
	problems = []
	raw = path.read_bytes()
	try:
		text = raw.decode("ascii")
	except UnicodeDecodeError as e:
		return [f"non-ASCII byte at offset {e.start}"]
	check_color = path.name not in ("theme.css", "codicons.css", "build.py")
	for number, line in enumerate(text.split("\n"), 1):
		if path.suffix in INDENT_SUFFIXES and re.match(r"^ +\S", line):
			problems.append(f"{number}: indented with spaces")
		if line.rstrip("\r") != line.rstrip(" \t\r") and line.strip():
			problems.append(f"{number}: trailing whitespace")
		if check_color and RAW_COLOR.search(line):
			problems.append(f"{number}: raw color outside theme.css: {line.strip()[:80]}")
	return problems


def lint():
	failed = False
	for path in sorted(FRONTEND.rglob("*")):
		if path.suffix not in TEXT_SUFFIXES or "screenshots" in path.parts:
			continue
		for problem in lint_file(path):
			failed = True
			print(f"{path.relative_to(REPO)}:{problem}")
	if failed:
		sys.exit("lint: failed")
	print("lint: ok")


def shots(only=""):
	from playwright.sync_api import sync_playwright
	SHOT_DIR.mkdir(exist_ok=True)
	with sync_playwright() as p:
		browser = p.chromium.launch()
		for page_name, query, shot, sizes in SHOTS:
			if not shot.startswith(only):
				continue
			for label, width, height, scale, mobile in sizes:
				context = browser.new_context(viewport={"width": width, "height": height}, device_scale_factor=scale, is_mobile=mobile, has_touch=mobile)
				page = context.new_page()
				errors = []
				page.on("pageerror", lambda e: errors.append(str(e)))
				page.on("console", lambda m: errors.append(m.text) if m.type == "error" else None)
				page.goto((MOCKS / page_name).as_uri() + query)
				page.wait_for_function("document.documentElement.dataset.ready === '1'")
				page.evaluate("document.fonts.ready")
				out = SHOT_DIR / f"{shot}-{label}.png"
				page.screenshot(path=str(out), full_page=page_name.startswith("00-"))
				context.close()
				if errors:
					sys.exit(f"shots: {page_name}{query} at {label}: " + "; ".join(errors))
				print(f"shots: {out.relative_to(REPO)}")
		browser.close()


def main():
	command = sys.argv[1] if len(sys.argv) > 1 else "all"
	only = sys.argv[2] if len(sys.argv) > 2 else ""
	if command in ("icons", "all"):
		build_icons()
	if command in ("lint", "all"):
		lint()
	if command in ("shots", "all"):
		shots(only)
	if command not in ("icons", "lint", "shots", "all"):
		sys.exit(__doc__)


if __name__ == "__main__":
	main()
