# Writes forwarders.h: for each object a D3D12 program hands to the capture library (device, command queue, command
# list, DXGI factory, swap chain), a class implementing the newest interface version of the Windows SDK whose every
# method forwards to the runtime's object of the version that declared it (docs/22 "Capture"). The proxies in
# wrappers.cpp derive from these and override the methods a capture records. Run it again when the SDK changes:
#   python gen_wrappers.py [--sdk "C:/Program Files (x86)/Windows Kits/10/Include/10.0.26100.0"]
import argparse
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))

FAMILIES = [
	# class name, versions (oldest first), headers
	("DeviceForwarder", ["ID3D12Device"] + [f"ID3D12Device{i}" for i in range(1, 15)], ["um/d3d12.h"]),
	("QueueForwarder", ["ID3D12CommandQueue"], ["um/d3d12.h"]),
	("ListForwarder", ["ID3D12CommandList", "ID3D12GraphicsCommandList"] + [f"ID3D12GraphicsCommandList{i}" for i in range(1, 11)], ["um/d3d12.h"]),
	("FactoryForwarder", ["IDXGIFactory", "IDXGIFactory1", "IDXGIFactory2", "IDXGIFactory3", "IDXGIFactory4", "IDXGIFactory5", "IDXGIFactory6", "IDXGIFactory7"],
		["shared/dxgi.h", "shared/dxgi1_2.h", "shared/dxgi1_3.h", "shared/dxgi1_4.h", "shared/dxgi1_5.h", "shared/dxgi1_6.h"]),
	("SwapChainForwarder", ["IDXGISwapChain", "IDXGISwapChain1", "IDXGISwapChain2", "IDXGISwapChain3", "IDXGISwapChain4"],
		["shared/dxgi.h", "shared/dxgi1_2.h", "shared/dxgi1_3.h", "shared/dxgi1_4.h", "shared/dxgi1_5.h"]),
]

SKIP = {"QueryInterface", "AddRef", "Release"}


def newest_sdk():
	roots = sorted(glob.glob("C:/Program Files (x86)/Windows Kits/10/Include/10.*"))
	if not roots:
		raise SystemExit("no Windows SDK found; pass --sdk")
	return roots[-1]


def strip_sal(text):
	# SAL annotations: identifiers starting with '_' and ending with '_', optionally followed by a (balanced) group.
	out = []
	i = 0
	while i < len(text):
		m = re.match(r"_[A-Za-z0-9_]*_\b", text[i:])
		if m and (i == 0 or not (text[i - 1].isalnum() or text[i - 1] == "_")):
			i += m.end()
			j = i
			while j < len(text) and text[j] == " ":
				j += 1
			if j < len(text) and text[j] == "(":
				depth = 0
				while j < len(text):
					if text[j] == "(":
						depth += 1
					elif text[j] == ")":
						depth -= 1
						if depth == 0:
							j += 1
							break
					j += 1
				i = j
			continue
		out.append(text[i])
		i += 1
	return "".join(out)


def interfaces(text):
	"""{name: (base, [(return, method, params)])} from the C++ interface definitions, the _MSC_VER branches only."""
	found = {}
	for m in re.finditer(r"MIDL_INTERFACE\(\"[0-9A-Fa-f-]+\"\)\s*\n\s*(\w+)\s*:\s*public\s+(\w+)\s*\{\s*public:(.*?)\n\s*\};", text, re.S):
		name, base, body = m.group(1), m.group(2), m.group(3)
		lines = []
		skipping = False
		for line in body.split("\n"):
			stripped = line.strip()
			if stripped.startswith("#if"):
				skipping = "_MSC_VER" not in stripped
				continue
			if stripped.startswith("#else"):
				skipping = True
				continue
			if stripped.startswith("#endif"):
				skipping = False
				continue
			if not skipping:
				lines.append(line)
		cleaned = strip_sal(re.sub(r"/\*.*?\*/", "", "\n".join(lines), flags=re.S))
		methods = []
		for mm in re.finditer(r"virtual\s+(.*?)\s*STDMETHODCALLTYPE\s+(\w+)\s*\((.*?)\)\s*(const\s*)?=\s*0\s*;", cleaned, re.S):
			ret = " ".join(mm.group(1).split())
			params = " ".join(mm.group(3).split())
			methods.append((ret, mm.group(2), params))
		found[name] = (base, methods)
	return found


def split_params(params):
	if params.strip() in ("", "void"):
		return []
	parts, depth, current = [], 0, ""
	for c in params:
		if c in "([":
			depth += 1
		elif c in ")]":
			depth -= 1
		if c == "," and depth == 0:
			parts.append(current.strip())
			current = ""
		else:
			current += c
	if current.strip():
		parts.append(current.strip())
	return parts


def param_name(param):
	without_array = re.sub(r"\[[^\]]*\]\s*$", "", param).strip()
	return re.findall(r"\w+", without_array)[-1]


def chain(all_ifaces, name):
	order = []
	while name in all_ifaces:
		order.append(name)
		name = all_ifaces[name][0]
	order.append(name)   # IUnknown or a base not parsed here
	return list(reversed(order))


def generate(sdk):
	texts = {}
	for _, _, headers in FAMILIES:
		for header in headers:
			if header not in texts:
				with open(os.path.join(sdk, header), encoding="utf-8", errors="replace") as f:
					texts[header] = f.read()
	all_ifaces = {}
	for text in texts.values():
		all_ifaces.update(interfaces(text))
	out = ["// Generated by gen_wrappers.py from the Windows SDK headers; do not edit. Each class forwards every method of",
		"// the newest interface version to the runtime's object of the version that declared the method.", "#pragma once", "",
		"#include <d3d12.h>", "#include <dxgi1_6.h>", "", "namespace fb::capture", "{"]
	for cls, versions, _ in FAMILIES:
		newest = versions[-1]
		order = chain(all_ifaces, newest)
		out.append(f"\tclass {cls} : public {newest}")
		out.append("\t{")
		out.append("\tpublic:")
		out.append(f"\t\tstatic constexpr int kVersions = {len(versions)};")
		out.append("\t\t// The runtime's object as each version (null for versions it does not support).")
		for i, v in enumerate(versions):
			out.append(f"\t\t{v}* real{i}_ = nullptr;")
		out.append("\t\tvoid* RealVersion(int version) const {")
		out.append("\t\t\tswitch (version) {")
		for i in range(len(versions)):
			out.append(f"\t\t\t\tcase {i}: return real{i}_;")
		out.append("\t\t\t\tdefault: return nullptr;")
		out.append("\t\t\t}")
		out.append("\t\t}")
		out.append("\t\tstatic const IID& VersionIid(int version) {")
		out.append("\t\t\tswitch (version) {")
		for i, v in enumerate(versions):
			out.append(f"\t\t\t\tcase {i}: return __uuidof({v});")
		out.append(f"\t\t\t\tdefault: return __uuidof({versions[0]});")
		out.append("\t\t\t}")
		out.append("\t\t}")
		out.append("")
		for iface in order:
			if iface not in all_ifaces:
				continue
			# Methods are called on the version that declared them, or the oldest version of the family for methods
			# of base interfaces (ID3D12Object, IDXGIObject, ...).
			target = versions.index(iface) if iface in versions else 0
			for ret, method, params in all_ifaces[iface][1]:
				if method in SKIP:
					continue
				names = ", ".join(param_name(p) for p in split_params(params))
				decl_params = params if params.strip() else "void"
				call = f"real{target}_->{method}({names})"
				body = f"return {call};" if ret != "void" else f"{call};"
				out.append(f"\t\t{ret} STDMETHODCALLTYPE {method}({decl_params}) override {{ {body} }}")
		out.append("\t};")
		out.append("")
	out.append("}")
	return "\n".join(out) + "\n"


def main():
	parser = argparse.ArgumentParser()
	parser.add_argument("--sdk", default="")
	options = parser.parse_args()
	sdk = options.sdk or newest_sdk()
	text = generate(sdk)
	path = os.path.join(HERE, "forwarders.h")
	with open(path, "w", encoding="ascii", errors="replace", newline="\n") as f:
		f.write(text)
	print(f"wrote {path} from {sdk}")


if __name__ == "__main__":
	main()
