	u32 AspectsOf(VkFormat format) {
		switch (format) {
			case VK_FORMAT_D16_UNORM:
			case VK_FORMAT_X8_D24_UNORM_PACK32:
			case VK_FORMAT_D32_SFLOAT:
				return VK_IMAGE_ASPECT_DEPTH_BIT;
			case VK_FORMAT_S8_UINT: return VK_IMAGE_ASPECT_STENCIL_BIT;
			case VK_FORMAT_D16_UNORM_S8_UINT:
			case VK_FORMAT_D24_UNORM_S8_UINT:
			case VK_FORMAT_D32_SFLOAT_S8_UINT:
				return VK_IMAGE_ASPECT_DEPTH_BIT | VK_IMAGE_ASPECT_STENCIL_BIT;
			default: return VK_IMAGE_ASPECT_COLOR_BIT;
		}
	}

	DXGI_FORMAT DxgiOf(VkFormat format, VkImageAspectFlagBits aspect) {
		if (aspect == VK_IMAGE_ASPECT_STENCIL_BIT) return (AspectsOf(format) & VK_IMAGE_ASPECT_STENCIL_BIT) ? DXGI_FORMAT_R8_UINT : DXGI_FORMAT_UNKNOWN;
		switch (format) {
			case VK_FORMAT_D16_UNORM:
			case VK_FORMAT_D16_UNORM_S8_UINT:
				return DXGI_FORMAT_D16_UNORM;
			// A copy of a 24-bit depth aspect is 32 bits a texel, the depth in the low 24.
			case VK_FORMAT_X8_D24_UNORM_PACK32:
			case VK_FORMAT_D24_UNORM_S8_UINT:
				return DXGI_FORMAT_R24_UNORM_X8_TYPELESS;
			case VK_FORMAT_D32_SFLOAT:
			case VK_FORMAT_D32_SFLOAT_S8_UINT:
				return DXGI_FORMAT_D32_FLOAT;
			default: break;
		}
		for (const FormatPair& pair : kColor)
			if (pair.vk == format) return pair.dxgi;
		return DXGI_FORMAT_UNKNOWN;
	}

	const FormatInfo* FormatOf(VkFormat format, VkImageAspectFlagBits aspect) {
		const DXGI_FORMAT dxgi = DxgiOf(format, aspect);
		return dxgi == DXGI_FORMAT_UNKNOWN ? nullptr : DxgiFormat(dxgi);
	}

	FormatBlock BlockOf(VkFormat format, VkImageAspectFlagBits aspect) {
		const FormatInfo* info = FormatOf(format, aspect);
		if (!info) return {0, 1, 1};
		return IsBlock(info->codec) ? FormatBlock{info->bytes, 4, 4} : FormatBlock{info->bytes, 1, 1};
	}
