namespace Scripting
{
	/// The addresses of a host's symbols under the interface's names (docs/runtime/04 section 6.1).
	class HostSymbolTable
	{
	public:
		/// The table compiled into the host image (`__c4_script_table`), paired with `host`'s names. Empty, with the
		/// reason, when the build ids or the counts differ (the interface is another build's).
		static std::optional<HostSymbolTable> Read(const HostInterface& host, const void* table, std::string* error);

		/// The address of `name`, or null when the host has no such symbol.
		void* Find(const std::string& name) const;
		template <typename F> F Function(const std::string& name) const { return reinterpret_cast<F>(Find(name)); }

	private:
		std::unordered_map<std::string, void*> m_Addresses;
	};

	/// The memory a linked script's code and data occupy: its image base is `low`.
	struct ScriptImage
	{
		uintptr_t low = 0;
		uintptr_t high = 0;
	};

	/// One script linked into the running program: in memory by its own JIT, or as a DLL (Script/ScriptDll.h).
	/// Destroying it frees exactly its code and data, and removes its unwind tables and its image.
	class LinkedScript
	{
	public:
		LinkedScript() = default;
		virtual ~LinkedScript() = default;
		LinkedScript(const LinkedScript&) = delete;
		LinkedScript& operator=(const LinkedScript&) = delete;

		/// The address of the script's symbol `name`, or null when it has none.
		virtual void* Find(const std::string& name) const = 0;
		virtual const ScriptImage& Image() const = 0;
		/// Where `address` is, by its module and function (`ied.git#3-1!WritesNull+0x12`); empty when the script's
		/// code has no symbols to name it by.
		virtual std::string Describe(uint64 address) const { return ""; }
	};

	/// The target machine scripts are compiled for, the one the JIT generates code with: the host's processor
	/// (`target`, D-62), so host and script pass vectors alike, with emulated thread storage (a JIT image has no PE
	/// TLS directory).
	std::unique_ptr<llvm::TargetMachine> ScriptTargetMachine(const CpuTarget& target, std::string* error);

	/// The machine a debug script's DLL is compiled for (Script/ScriptDll.h): the same processor and thread storage, and
	/// position-independent code of the small model, as any image's (the JIT's large model writes every address into the
	/// code, and a static one writes 32-bit absolute addresses, which a DLL above 4 GiB cannot hold).
	std::unique_ptr<llvm::TargetMachine> ScriptDllTargetMachine(const CpuTarget& target, bool optimize, std::string* error);

	/// What a script links from: the module it compiled to, or the machine code an earlier link of it generated (a
	/// ScriptCache entry's), used as it is.
	struct ScriptCode
	{
		std::unique_ptr<llvm::LLVMContext> context;
		std::unique_ptr<llvm::Module> module;
		bool optimize = true;   // the module's code is generated by the fast code generator when it is not
		std::string object;     // when there is no module
	};

	/// Links `code` into the running program (docs/runtime/04 section 6): one block per object, its `.pdata`
	/// registered against the block's base, an in-image personality routine, and its undefined names resolved through
	/// the host table, then the compiler's support functions (memcpy, __chkstk, the math functions), then the
	/// exports of the process's DLLs. Every definition is generated before it returns; `generated`, when given, gets
	/// the machine code generated from a module. Empty, with the reason, when it does not link.
	std::unique_ptr<LinkedScript> LinkScript(ScriptCode code, const HostSymbolTable& host, const CpuTarget& target, std::string* generated,
		std::string* error);
} // namespace Scripting
