"""nuke.lock: the exact commit of every versioned package a workspace uses, the exact version and hash of every NuGet
package (nuget.py), and a digest of the requirements the packages were chosen for. Generated, so it lives in the packages folder (packages/nuke.lock) and is ignored with it: nuke.toml is what
a workspace commits, and each checkout chooses its versions from it on its first command. Read on every command: while
it matches the manifests and the packages are in place, nothing is resolved and no git process starts. A lock at the
workspace's root (Nuke before 2026-10-27) moves into the folder the first time it is read."""

import os
import tomllib
from dataclasses import dataclass, field

from .. import fsutil
from ..errors import NukeError

FILE = "nuke.lock"
FORMAT = 1
HEADER = ("# nuke.lock - the exact versions of the packages this workspace builds with (Nuke/README.md section 12).\n"
	"# Generated by Nuke from nuke.toml, not committed: `nuke package update` chooses them again.\n")


@dataclass(frozen=True)
class Locked:
	url: str            # the source repository
	source: str         # its folder under packages/
	line: str           # the versioned package's path ("" for the repository)
	version: str
	commit: str
	uses: tuple = ()    # the package paths of it the workspace uses

	@property
	def key(self):
		from .store import url_key
		return (url_key(self.url), self.line)


@dataclass(frozen=True)
class LockedNuget:
	id: str             # the NuGet package id as the manifests write it
	version: str
	sha256: str         # of the .nupkg, checked whenever it is downloaded again


@dataclass
class Lock:
	digest: str = ""
	packages: list = field(default_factory=list)
	nuget: list = field(default_factory=list)      # LockedNuget, one per package id

	def find_nuget(self, package_id):
		return next((n for n in self.nuget if n.id.lower() == package_id.lower()), None)

	def find(self, key):
		return next((p for p in self.packages if p.key == key), None)


def path_of(spec):
	"""The lock of a workspace (a WorkspaceSpec): in its packages folder."""
	return fsutil.join(spec.dir, spec.packages_dir, FILE)


def _old_path(spec):
	return fsutil.join(spec.dir, FILE)


def exists(spec):
	return os.path.isfile(path_of(spec)) or os.path.isfile(_old_path(spec))


def read(spec):
	path = path_of(spec)
	if not os.path.isfile(path) and os.path.isfile(_old_path(spec)):
		os.makedirs(os.path.dirname(path), exist_ok=True)
		os.replace(_old_path(spec), path)
	if not os.path.isfile(path):
		return None
	try:
		with open(path, "rb") as f:
			data = tomllib.load(f)
	except (OSError, tomllib.TOMLDecodeError) as error:
		raise NukeError(f"{path}: {error} (delete it and run `nuke package update` to write it again)") from None
	if data.get("format") != FORMAT:
		raise NukeError(f"{path}: written by another Nuke (format {data.get('format')}); `nuke package update` writes it again")
	lock = Lock(digest=str(data.get("requirements", "")))
	for entry in data.get("package", []):
		try:
			lock.packages.append(Locked(entry["source"], entry["name"], entry.get("path", ""), entry["version"],
				entry["commit"], tuple(entry.get("uses", ()))))
		except (KeyError, TypeError):
			raise NukeError(f"{path}: a [[package]] entry lacks source, name, version or commit; `nuke package update` writes it again") from None
	for entry in data.get("nuget", []):
		try:
			lock.nuget.append(LockedNuget(entry["id"], entry["version"], entry["sha256"]))
		except (KeyError, TypeError):
			raise NukeError(f"{path}: a [[nuget]] entry lacks id, version or sha256; `nuke package update` writes it again") from None
	return lock


def _string(text):
	return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(lock):
	lines = [HEADER, f"format = {FORMAT}", f"requirements = {_string(lock.digest)}", ""]
	for entry in sorted(lock.packages, key=lambda p: (p.source.lower(), p.line.lower())):
		lines += [
			"[[package]]",
			f"name = {_string(entry.source)}",
			f"source = {_string(entry.url)}",
			f"path = {_string(entry.line)}",
			f"version = {_string(entry.version)}",
			f"commit = {_string(entry.commit)}",
			"uses = [" + ", ".join(_string(u) for u in sorted(entry.uses)) + "]",
			"",
		]
	for entry in sorted(lock.nuget, key=lambda n: n.id.lower()):
		lines += ["[[nuget]]", f"id = {_string(entry.id)}", f"version = {_string(entry.version)}", f"sha256 = {_string(entry.sha256)}", ""]
	return "\n".join(lines)


def write(spec, lock):
	"""Writes the lock when it changed; True if it did."""
	return fsutil.write_if_changed(path_of(spec), render(lock))
